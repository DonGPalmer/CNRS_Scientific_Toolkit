#!/usr/bin/env python3
"""Fail closed unless v0.19 source/assets match an out-of-band approval manifest.

Trust comes from the separately governed publication environment's manifest
digest, never from a sidecar generated by this build. This verifies identity;
it does not decide whether a human approval is valid.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

VERSION = "0.19.0"
TAG = "v0.19.0"
ASSETS = ("cnrs-0.19.0-py3-none-any.whl", "cnrs-0.19.0.tar.gz")


def _unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate manifest key: {key}")
        result[key] = value
    return result


def _hex(value, length):
    return isinstance(value, str) and re.fullmatch(r"[0-9a-f]{" + str(length) + r"}", value) is not None


def load_approval(path: Path, approved_digest: str) -> dict:
    if not _hex(approved_digest, 64):
        raise ValueError("a separately approved manifest SHA256 is required")
    raw = path.read_bytes()
    if hashlib.sha256(raw).hexdigest() != approved_digest:
        raise ValueError("manifest does not match the approved SHA256")
    data = json.loads(raw, object_pairs_hook=_unique_object)
    keys = {"schema", "version", "tag", "commit", "tree", "assets", "approval_record"}
    if not isinstance(data, dict) or set(data) != keys:
        raise ValueError("invalid approval manifest fields")
    if type(data["schema"]) is not int or data["schema"] != 1 or data["version"] != VERSION or data["tag"] != TAG:
        raise ValueError("unsupported approval schema/version/tag")
    if not _hex(data["commit"], 40) or not _hex(data["tree"], 40):
        raise ValueError("approved commit and tree must be full Git SHA1 identities")
    if not isinstance(data["approval_record"], str) or not data["approval_record"].strip():
        raise ValueError("a durable author approval record is required")
    assets = data["assets"]
    if not isinstance(assets, dict) or set(assets) != set(ASSETS) or not all(_hex(v, 64) for v in assets.values()):
        raise ValueError("exactly the two approved asset SHA256 identities are required")
    return data


def verify_source(repo: Path, approval: dict) -> None:
    def rev(ref):
        return subprocess.check_output(["git", "rev-parse", "--verify", ref], cwd=repo, text=True).strip()
    if rev("HEAD") != approval["commit"] or rev("HEAD^{tree}") != approval["tree"]:
        raise ValueError("checkout does not match approved commit/tree")
    if rev("refs/tags/" + TAG + "^{commit}") != approval["commit"]:
        raise ValueError("release tag does not identify the approved commit")
    if subprocess.check_output(["git", "status", "--porcelain", "--untracked-files=no"], cwd=repo, text=True):
        raise ValueError("tracked checkout differs from approved Git source")


def verify_assets(directory: Path, approval: dict) -> None:
    for name in ASSETS:
        if hashlib.sha256((directory / name).read_bytes()).hexdigest() != approval["assets"][name]:
            raise ValueError(f"asset differs from approved bytes: {name}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--approved-sha256", required=True)
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--directory", type=Path)
    args = parser.parse_args()
    approval = load_approval(args.manifest, args.approved_sha256)
    verify_source(args.repo, approval)
    if args.directory is not None:
        verify_assets(args.directory, approval)
    print("v0.19.0 approved source" + (" and artifact bytes" if args.directory else "") + " verified")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
